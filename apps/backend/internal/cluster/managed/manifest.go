// Request is one addon to materialise in a tenant namespace.
// Replicas are always 1. StorageMB <= 0 selects the default 1Gi volume.
type Request struct {
	Namespace            string
	TenantID             string
	ProjectID            string
	ServiceID            string
	Engine               string
	StorageMB            int
	CPURequestMillicores int
	CPULimitMillicores   int
	MemoryRequestMB      int
	MemoryLimitMB        int
}

func (r Request) addon() (Addon, error) {
	cat := DefaultCatalog()
	return lookup(cat, r.Engine)
}

func lookup(cat Catalog, engine string) (Addon, error) {
	if cat == nil {
		cat = DefaultCatalog()
	}
	a, ok := cat.AddonFor(engine)
	if !ok {
		return Addon{}, fmt.Errorf("managed: unknown engine %q", engine)
	}
	if a.Port < 1 || a.Port > 65535 || strings.TrimSpace(a.Image) == "" {
		return Addon{}, fmt.Errorf("managed: catalog entry for %q is incomplete", engine)
	}
	return a, nil
}

func (r Request) labels() (map[string]string, error) {
	name, err := ObjectName(r.ServiceID)
	if err != nil {
		return nil, err
	}
	labels := map[string]string{
		workloads.LabelAppName:      name,
		workloads.LabelAppInstance:  name,
		workloads.LabelAppManaged:   workloads.ValueManagedBy,
		workloads.LabelAppPartOf:    workloads.ValuePartOf,
		workloads.LabelAppComponent: "addon",
		workloads.LabelManagedBy:    workloads.ValueManagedBy,
	}
	if t := strings.TrimSpace(r.TenantID); t != "" {
		labels[workloads.LabelTenant] = t
	}
	if p := strings.TrimSpace(r.ProjectID); p != "" {
		labels[workloads.LabelProject] = p
	}
	labels[workloads.LabelService] = strings.ToLower(strings.TrimSpace(r.ServiceID))
	return labels, nil
}

func selectorLabels(serviceID string) map[string]string {
	name, _ := ObjectName(serviceID)
	return map[string]string{
		workloads.LabelAppName:      name,
		workloads.LabelAppComponent: "addon",
		workloads.LabelService:      strings.ToLower(strings.TrimSpace(serviceID)),
	}
}

// Credentials is the connection material stored in the addon Secret.
type Credentials struct {
	Username string
	Password string
	Database string
	Host     string
	Port     int32
	URL      string
}

func credentials(engine, namespace, serviceID, password string, port int32) (Credentials, error) {
	host, err := ServiceDNS(namespace, serviceID)
	if err != nil {
		return Credentials{}, err
	}
	user, database := "postgres", "postgres"
	scheme := "postgres"
	if strings.EqualFold(engine, EngineRedis) {
		user, database = "default", ""
		scheme = "redis"
	}
	u := &url.URL{
		Scheme: scheme,
		User:   url.UserPassword(user, password),
		Host:   net.JoinHostPort(host, strconv.Itoa(int(port))),
	}
	if scheme == "postgres" {
		u.Path = "/" + database
		u.RawQuery = "sslmode=disable"
	} else {
		u.Path = "/0"
	}
	return Credentials{
		Username: user,
		Password: password,
		Database: database,
		Host:     host,
		Port:     port,
		URL:      u.String(),
	}, nil
}

func secretData(c Credentials) map[string][]byte {
	data := map[string][]byte{
		"host":     []byte(c.Host),
		"port":     []byte(strconv.Itoa(int(c.Port))),
		"username": []byte(c.Username),
		"password": []byte(c.Password),
		"url":      []byte(c.URL),
	}
	if c.Database != "" {
		data["database"] = []byte(c.Database)
	}
	return data
}

// BuildSecret returns the addon Secret. password is stored as given and is not
// regenerated by this function.
func BuildSecret(req Request, password string, addon Addon) (*corev1.Secret, error) {
	name, err := ObjectName(req.ServiceID)
	if err != nil {
		return nil, err
	}
	labels, err := req.labels()
	if err != nil {
		return nil, err
	}
	cred, err := credentials(addon.Engine, req.Namespace, req.ServiceID, password, addon.Port)
	if err != nil {
		return nil, err
	}
	return &corev1.Secret{
		ObjectMeta: metav1.ObjectMeta{
			Name:      name,
			Namespace: req.Namespace,
			Labels:    labels,
		},
		Type: corev1.SecretTypeOpaque,
		Data: secretData(cred),
	}, nil
}

// BuildService returns the headless Service a StatefulSet uses for its stable
// network identity. The connection URL uses this Service's cluster DNS name.
func BuildService(req Request, addon Addon) (*corev1.Service, error) {
	name, err := ObjectName(req.ServiceID)
	if err != nil {
		return nil, err
	}
	labels, err := req.labels()
	if err != nil {
		return nil, err
	}
	return &corev1.Service{
		ObjectMeta: metav1.ObjectMeta{
			Name:      name,
			Namespace: req.Namespace,
			Labels:    labels,
		},
		Spec: corev1.ServiceSpec{
			ClusterIP: corev1.ClusterIPNone,
			Selector:  selectorLabels(req.ServiceID),
			Ports: []corev1.ServicePort{{
				Name:       "db",
				Protocol:   corev1.ProtocolTCP,
				Port:       addon.Port,
				TargetPort: intstr.FromInt32(addon.Port),
			}},
		},
	}, nil
}

func storageQuantity(mb int) resource.Quantity {
	if mb <= 0 {
		return resource.MustParse(DefaultStorage)
	}
	return resource.MustParse(fmt.Sprintf("%dMi", mb))
}

func computeResources(req Request) corev1.ResourceRequirements {
	cpuReq, cpuLim := req.CPURequestMillicores, req.CPULimitMillicores
	memReq, memLim := req.MemoryRequestMB, req.MemoryLimitMB
	if cpuReq <= 0 {
		cpuReq = 100
	}
	if cpuLim <= 0 {
		cpuLim = 500
	}
	if memReq <= 0 {
		memReq = 256
	}
	if memLim <= 0 {
		memLim = 512
	}
	if cpuReq > cpuLim {
		cpuReq = cpuLim
	}
	if memReq > memLim {
		memReq = memLim
	}
	return corev1.ResourceRequirements{
		Requests: corev1.ResourceList{
			corev1.ResourceCPU:    resource.MustParse(fmt.Sprintf("%dm", cpuReq)),
			corev1.ResourceMemory: resource.MustParse(fmt.Sprintf("%dMi", memReq)),
		},
		Limits: corev1.ResourceList{
			corev1.ResourceCPU:    resource.MustParse(fmt.Sprintf("%dm", cpuLim)),
			corev1.ResourceMemory: resource.MustParse(fmt.Sprintf("%dMi", memLim)),
		},
	}
}

func secretKey(name, key string) *corev1.EnvVarSource {
	return &corev1.EnvVarSource{
		SecretKeyRef: &corev1.SecretKeySelector{
			LocalObjectReference: corev1.LocalObjectReference{Name: name},
			Key:                  key,
		},
	}
}

func container(req Request, addon Addon, secretName string) corev1.Container {
	probe := readinessProbe(addon.Engine)
	c := corev1.Container{
		Name:            addon.Engine,
		Image:           addon.Image,
		ImagePullPolicy: corev1.PullIfNotPresent,
		Ports: []corev1.ContainerPort{{
			Name:          "db",
			ContainerPort: addon.Port,
			Protocol:      corev1.ProtocolTCP,
		}},
		Resources: computeResources(req),
		SecurityContext: &corev1.SecurityContext{
			AllowPrivilegeEscalation: boolPtr(false),
			ReadOnlyRootFilesystem:   boolPtr(false),
			Capabilities:             &corev1.Capabilities{Drop: []corev1.Capability{"ALL"}},
		},
		ReadinessProbe: probe,
		LivenessProbe:  livenessProbe(addon.Engine),
	}
	switch strings.ToLower(addon.Engine) {
	case EnginePostgres:
		c.Env = []corev1.EnvVar{
			{Name: "POSTGRES_USER", Value: "postgres"},
			{Name: "POSTGRES_DB", Value: "postgres"},
			{Name: "PGDATA", Value: "/var/lib/postgresql/data/pgdata"},
			{Name: "POSTGRES_PASSWORD", ValueFrom: secretKey(secretName, "password")},
		}
		c.VolumeMounts = []corev1.VolumeMount{{
			Name:      VolumeName,
			MountPath: "/var/lib/postgresql/data",
		}}
	default:
		c.Env = []corev1.EnvVar{
			{Name: "REDIS_PASSWORD", ValueFrom: secretKey(secretName, "password")},
			{Name: "REDISCLI_AUTH", ValueFrom: secretKey(secretName, "password")},
		}
		// $(REDIS_PASSWORD) is expanded by the kubelet from the env above.
		c.Args = []string{"--appendonly", "yes", "--requirepass", "$(REDIS_PASSWORD)"}
		c.VolumeMounts = []corev1.VolumeMount{{
			Name:      VolumeName,
			MountPath: "/data",
		}}
	}
	return c
}

func readinessProbe(engine string) *corev1.Probe {
	cmd := []string{"pg_isready", "-U", "postgres", "-d", "postgres"}
	if strings.EqualFold(engine, EngineRedis) {
		cmd = []string{"redis-cli", "ping"}
	}
	return &corev1.Probe{
		ProbeHandler:        corev1.ProbeHandler{Exec: &corev1.ExecAction{Command: cmd}},
		InitialDelaySeconds: 5,
		PeriodSeconds:       5,
		TimeoutSeconds:      3,
		FailureThreshold:    6,
	}
}

func livenessProbe(engine string) *corev1.Probe {
	p := readinessProbe(engine)
	p.InitialDelaySeconds = 30
	p.PeriodSeconds = 10
	p.FailureThreshold = 6
	return p
}

// BuildStatefulSet returns a 1-replica StatefulSet. The PVC is declared only
// via volumeClaimTemplates so a later update cannot replace the disk.
func BuildStatefulSet(req Request, addon Addon) (*appsv1.StatefulSet, error) {
	name, err := ObjectName(req.ServiceID)
	if err != nil {
		return nil, err
	}
	labels, err := req.labels()
	if err != nil {
		return nil, err
	}
	replicas := int32(1)
	uid := int64(999)
	storage := storageQuantity(req.StorageMB)
	return &appsv1.StatefulSet{
		ObjectMeta: metav1.ObjectMeta{
			Name:      name,
			Namespace: req.Namespace,
			Labels:    labels,
		},
		Spec: appsv1.StatefulSetSpec{
			Replicas:    &replicas,
			ServiceName: name,
			Selector:    &metav1.LabelSelector{MatchLabels: selectorLabels(req.ServiceID)},
			Template: corev1.PodTemplateSpec{
				ObjectMeta: metav1.ObjectMeta{Labels: labels},
				Spec: corev1.PodSpec{
					AutomountServiceAccountToken: boolPtr(false),
					SecurityContext: &corev1.PodSecurityContext{
						RunAsNonRoot: boolPtr(true),
						RunAsUser:    &uid,
						RunAsGroup:   &uid,
						FSGroup:      &uid,
						SeccompProfile: &corev1.SeccompProfile{
							Type: corev1.SeccompProfileTypeRuntimeDefault,
						},
					},
					Containers: []corev1.Container{container(req, addon, name)},
				},
			},
			VolumeClaimTemplates: []corev1.PersistentVolumeClaim{{
				ObjectMeta: metav1.ObjectMeta{
					Name:   VolumeName,
					Labels: labels,
				},
				Spec: corev1.PersistentVolumeClaimSpec{
					AccessModes: []corev1.PersistentVolumeAccessMode{corev1.ReadWriteOnce},
					Resources: corev1.VolumeResourceRequirements{
						Requests: corev1.ResourceList{corev1.ResourceStorage: storage},
					},
				},
			}},
			PersistentVolumeClaimRetentionPolicy: &appsv1.StatefulSetPersistentVolumeClaimRetentionPolicy{
				WhenDeleted: appsv1.DeletePersistentVolumeClaimRetentionPolicyType,
				WhenScaled:  appsv1.RetainPersistentVolumeClaimRetentionPolicyType,
			},
		},
	}, nil
}

func boolPtr(v bool) *bool { return &v }
